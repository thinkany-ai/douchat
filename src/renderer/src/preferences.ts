export type LanguagePreference = 'system' | InterfaceLanguage
export type Preferences = { language: LanguagePreference; appearance: 'system' | 'light' | 'dark'; fontSize: number }
const key = 'douchat.general'
function systemLanguage(): InterfaceLanguage {
  const locale = typeof navigator === 'undefined'
    ? 'en'
    : navigator.languages?.[0] || navigator.language
  return supportedInterfaceLanguage(locale)
}
export function resolveInterfaceLanguage(language: LanguagePreference): InterfaceLanguage {
  return language === 'system' ? systemLanguage() : language
}
function read(): Preferences {
  try {
    const saved = JSON.parse(localStorage.getItem(key) || '{}')
    return { language: saved.language === 'zh-CN' || saved.language === 'en' ? saved.language : 'system', appearance: ['light', 'dark'].includes(saved.appearance) ? saved.appearance : 'system', fontSize: Number.isInteger(saved.fontSize) && saved.fontSize >= 0 && saved.fontSize <= 4 ? saved.fontSize : 1 }
  } catch { return { language: 'system', appearance: 'system', fontSize: 1 } }
}
let current = read()
const listeners = new Set<() => void>()
const media = matchMedia('(prefers-color-scheme: dark)')
function apply(): void {
  document.documentElement.dataset.theme = current.appearance === 'system' ? (media.matches ? 'dark' : 'light') : current.appearance
  document.documentElement.lang = resolveInterfaceLanguage(current.language)
  document.documentElement.style.setProperty('--font-scale', String([0.85, 0.92, 1, 1.1, 1.2][current.fontSize]))
}
export function setPreferences(patch: Partial<Preferences>): void {
  current = { ...current, ...patch }
  localStorage.setItem(key, JSON.stringify(current))
  apply()
  listeners.forEach((notify) => notify())
}
window.addEventListener('storage', (event) => {
  if (event.key !== key) return
  current = read(); apply(); listeners.forEach((notify) => notify())
})
media.addEventListener('change', apply)
window.addEventListener('languagechange', () => {
  apply()
  if (current.language === 'system') listeners.forEach((notify) => notify())
})
apply()
export function usePreferences(): Preferences {
  return useSyncExternalStore((notify) => { listeners.add(notify); return () => { listeners.delete(notify) } }, () => current, () => current)
}
export function t(text: string): string {
  if (resolveInterfaceLanguage(current.language) !== 'zh-CN') return text
  const exact = translations[text]
  if (exact) return exact

  const patterns: Array<[RegExp, (...matches: string[]) => string]> = [
    [/^Could not complete desktop login \(HTTP (\d+)\)\. Return to the app and try again\.$/, (_all, status) => `客户端登录失败（HTTP ${status}），请返回客户端重新登录。`],
    [/^The owner of "(.+)" has disabled requests from group members\.$/, (_all, name) => `「${name}」的主人未开放群成员调用，请联系主人调整 Agent 权限。`],
    [/^Permissions for "(.+)" have not synchronized\. Ask the owner to reconnect\.$/, (_all, name) => `「${name}」的调用权限尚未同步，请主人重新连接后再试。`],
    [/^Runtime download failed \((\d+)\)\. Check your connection and try again\.$/, (_all, status) => `运行环境下载失败（${status}），请检查网络后重试。`],
    [/^(.+) could not deliver a message to another bot\.?$/, (_all, name) => `${name} 无法向其他智能体传递消息。`],
    [/^(.+) has no model to answer with\.?(?: (.*))?$/, (_all, name, detail) => `${name} 没有可用于回复的模型。${detail ?? ''}`],
    [/^(.+) finished without a text response\.?$/, (_all, name) => `${name} 未返回文字内容。`],
    [/^(?:429:\s*)?.*Douchat credit balance is insufficient.*$/i, () => 'Douchat 点数不足，暂时无法完成此请求。'],
    [/^Model (.+) is not available$/, (_all, model) => `模型 ${model} 当前不可用`],
    [/^Login service returned (\d+)\. Try again\.$/, (_all, status) => `登录服务返回 ${status}，请重试。`],
    [/^The gateway rejected the model list \((\d+)\)$/, (_all, status) => `模型服务拒绝了模型列表请求（${status}）`]
  ]
  for (const [pattern, replace] of patterns) {
    const match = pattern.exec(text)
    if (match) return replace(...match)
  }

  const prefixes: Array<[string, string]> = [
    ['Unexpected test response:', '测试返回了非预期内容，请检查启动参数：'],
    ['The model endpoint rejected the request', '模型服务拒绝了请求'],
    ['The model endpoint was not found', '未找到模型服务'],
    ['The model endpoint timed out', '模型服务请求超时'],
    ['The provider is rate limiting this key', '模型服务对当前密钥进行了限流'],
    ['The provider returned a server error', '模型服务返回服务器错误'],
    ['Could not reach the model endpoint', '无法连接模型服务'],
    ['Lost the connection to the model endpoint', '与模型服务的连接已中断'],
    ['The conversation could not finish', '对话未能完成']
  ]
  const prefix = prefixes.find(([source]) => text.startsWith(source))
  return prefix ? `${prefix[1]}${text.slice(prefix[0].length)}` : text
}
export function tr(text: string, values: Record<string, string | number>): string {
  return interpolate(t(text), values)
}
